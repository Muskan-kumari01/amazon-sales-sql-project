CREATE DATABASE AMAZON1_DATA;

CREATE TABLE AMAZON1_SALES(
  ORDER_ID INT PRIMARY KEY,
  ORDER_DATE DATE,
  PRODUCT_ID INT,
  PRODUCT_CATEGORY VARCHAR(20),
  PRICE FLOAT,
  DISCOUNT_PERCENT INT,
  QUANTITY_SOLD INT,
  CUSTOMER_REGION VARCHAR(50),
  PAYMENT_METHOD VARCHAR(40),
  RATING FLOAT,
  review_count INT,
  discounted_price FLOAT,
  total_revenue FLOAT
);

